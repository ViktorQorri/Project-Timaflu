"""Build reproducible Timaflu school-submission ZIP archives.

Only Git-tracked source files and the generated query report are packaged. Local configuration
secrets, caches, virtual environments and generated bytecode stay excluded.
The packages do not deploy or publish a production database.
"""
from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path
import subprocess
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED

from oplevering.validate_eer_schema import validate as validate_eer_schema

ROOT = Path(__file__).resolve().parents[1]
QUERY_REPORT = ROOT / "deliverables/query-output-per-screen.md"
QUERY_ARCHIVE_PATH = "Documentation/Architecture/query-output-per-screen.md"

ARCHIVES = {
    "timaflu-backend.zip": (
        ("code/backend/",),
        ("code/README.md", "README.MD"),
    ),
    "timaflu-frontend.zip": (
        ("code/frontend/",),
        ("code/README.md", "README.MD"),
    ),
    "timaflu-database-en-queries.zip": (
        ("code/database/",),
        (
            "eer.mwb",
            "Documentation/Architecture/eer-mysql-verified.svg",

        ),
    ),
    "timaflu-ontwerpen.zip": (
        (
            "Documentation/Architecture/screens/",
            "Documentation/Architecture/uml/",
        ),
        (
            "Documentation/Architecture/class-diagram-backend.puml",
            "Documentation/Architecture/class-diagram-backend.svg",
            "Documentation/brightspace/Product-description.md",
            "Documentation/brightspace/Current-processes.md",
            "Documentation/brightspace/Desired-process.md",
        ),
    ),
}


def tracked_paths():
    completed = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "-z"],
        check=True, capture_output=True,
    )
    return sorted(
        p.decode("utf-8") for p in completed.stdout.split(b"\0") if p
    )


def included(path, folders, fixed):
    return path in fixed or any(path.startswith(folder) for folder in folders)


def validate_query_report(document: bytes):
    """Reject stale, failed or incomplete screen evidence at packaging time."""
    report = document.decode("utf-8").replace("\r\n", "\n")
    tree = ast.parse((ROOT / "scripts/oplevering/audit_ui_queries.py").read_text(encoding="utf-8"))
    screen_values = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "SCREENS"
            for target in node.targets
        ):
            screen_values = ast.literal_eval(node.value)
            break
    if screen_values is None:
        raise RuntimeError("De actuele lijst met schermroutes ontbreekt in de audittool.")

    expected = [url for url, _ in screen_values]
    recorded = re.findall(r"^Scherm: (.+)$", report, re.M)
    if recorded != expected:
        raise RuntimeError("Het querydocument bevat niet alle actuele schermen in de juiste volgorde.")

    statuses = re.findall(r"^HTTP-status: (\d+)$", report, re.M)
    if len(statuses) != len(expected) or any(status != "200" for status in statuses):
        raise RuntimeError("Een of meer schermen in het querydocument zijn niet geslaagd.")

    queries = re.findall(r"^### Query \d+$", report, re.M)
    outputs = re.findall(r"^Resultaat: \d+ rij\(en\)", report, re.M)
    if not queries or len(queries) != len(outputs):
        raise RuntimeError("Een of meer queries in het document missen hun database-output.")
    designs = sorted((ROOT / "Documentation/Architecture/screens").glob("AD??_*.html"))
    images = ROOT / "deliverables/query-screens"
    design_titles = re.findall(r"(?m)^### (AD\d{2}): ", report)
    if len(designs) != 28 or len(design_titles) != 28:
        raise RuntimeError("Het querydocument moet alle 28 ontwerpschermen bevatten.")
    if len(set(design_titles)) != 28:
        raise RuntimeError("Een ontwerpscherm staat dubbel of ontbreekt.")
    generated_pdf = ROOT / "deliverables/query-output-per-screen.pdf"
    if not generated_pdf.is_file() or generated_pdf.stat().st_size < 30000:
        raise RuntimeError("Het complete, printbare querybewijs in PDF ontbreekt.")
    for design in designs:
        image = images / (design.stem + ".png")
        link = f"query-screens/{design.stem}.png"
        if not image.is_file() or image.stat().st_size < 5000 or link not in report:
            raise RuntimeError(f"Ontbrekende screenshot of documentkoppeling: {link}")
    if report.count("De databasewijziging is binnen een testtransactie gecontroleerd") != 37:
        raise RuntimeError("Het document moet 37 gecontroleerde formulieracties bevatten.")



def build(output_dir: Path):
    validate_eer_schema()
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = tracked_paths()
    resulting = {}
    for filename, (folders, fixed) in ARCHIVES.items():
        source_paths = [p for p in paths if included(p, folders, fixed)]
        if not source_paths:
            raise RuntimeError(f"No Git-tracked source for {filename}")
        archive = output_dir / filename
        generated_query_report = None
        if filename == "timaflu-database-en-queries.zip":
            if not QUERY_REPORT.is_file():
                raise RuntimeError(
                    "MySQL-queryrapport ontbreekt. Genereer eerst "
                    "deliverables/query-output-per-screen.md met "
                    "python scripts/oplevering/build_query_proof.py op een geïsoleerde testdatabase."
                )
            generated_query_report = QUERY_REPORT.read_bytes()
            validate_query_report(generated_query_report)
        with ZipFile(archive, "w", compression=ZIP_DEFLATED, compresslevel=9) as zipped:
            for relative in source_paths:
                file = ROOT / relative
                if not file.is_file():
                    raise RuntimeError(f"Missing tracked deliverable: {relative}")
                info = ZipInfo(relative, date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                zipped.writestr(info, file.read_bytes(), compress_type=ZIP_DEFLATED,
                                compresslevel=9)
            if generated_query_report is not None:
                info = ZipInfo(QUERY_ARCHIVE_PATH, date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                zipped.writestr(
                    info, generated_query_report, compress_type=ZIP_DEFLATED,
                    compresslevel=9,
                )
                # Screenshots are part of this same standalone database
                # submission so image links work after extracting the ZIP.
                pdf = ROOT / "deliverables/query-output-per-screen.pdf"
                pdf_info = ZipInfo("Documentation/Architecture/query-output-per-screen.pdf",
                                   date_time=(1980, 1, 1, 0, 0, 0))
                pdf_info.compress_type = ZIP_DEFLATED
                pdf_info.external_attr = 0o644 << 16
                zipped.writestr(pdf_info, pdf.read_bytes(),
                                compress_type=ZIP_DEFLATED, compresslevel=9)
                for screenshot in sorted((ROOT / "deliverables/query-screens").glob("AD??_*.png")):
                    relative = "Documentation/Architecture/query-screens/" + screenshot.name
                    image_info = ZipInfo(relative, date_time=(1980, 1, 1, 0, 0, 0))
                    image_info.compress_type = ZIP_DEFLATED
                    image_info.external_attr = 0o644 << 16
                    zipped.writestr(image_info, screenshot.read_bytes(),
                                    compress_type=ZIP_DEFLATED, compresslevel=9)
        resulting[filename] = (
            source_paths + [QUERY_ARCHIVE_PATH, "Documentation/Architecture/query-output-per-screen.pdf"] +
            ["Documentation/Architecture/query-screens/" + x.name
             for x in sorted((ROOT / "deliverables/query-screens").glob("AD??_*.png"))]
            if generated_query_report is not None else source_paths
        )
    return resulting


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=ROOT / "deliverables")
    args = parser.parse_args()
    for name, contents in build(args.output_dir).items():
        print(f"{name}: {len(contents)} files")


if __name__ == "__main__":
    main()
